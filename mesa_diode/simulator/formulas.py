# -*- coding: utf-8 -*-
"""Текст окна «Формулы и параметры» симулятора — редактируется только здесь.

Каждый элемент FORMULA_SECTIONS — это один раздел окна: (заголовок, текст).
Чтобы ДОБАВИТЬ новую формулу/раздел — допишите новый кортеж в конец списка.
Чтобы ИЗМЕНИТЬ существующую формулу — отредактируйте соответствующую строку
текста внутри вызова textwrap.dedent с многострочной строкой. Больше
НИЧЕГО менять не нужно — окно собирается автоматически функцией
build_formulas_text() и открывается методом MesaApp.open_formulas_window()
(см. simulator/app.py).
"""

import textwrap

FORMULA_SECTIONS = [
    ("1. Геометрия мезы", textwrap.dedent("""
        D  — диаметр мезы, мкм (вводится пользователем)
        h  — глубина/высота мезы, мкм (вводится пользователем; используется
             только для схемы — в текущей модели не влияет на ВАХ/ВФХ,
             т.к. применяется приближение резкого перехода без учёта
             боковой поверхности мезы)
        A  — площадь мезы, см²
             A = pi * (D/2)^2 ,  D переведено в см (D_см = D_мкм * 1e-4)
    """)),
    ("2. Диодное уравнение (диффузионный ток, Шокли)", textwrap.dedent("""
        J0 = q * ( Dp_Ge * pn0 / Lp_Ge  +  Dn_Si * np0 / Ln_Si )

        pn0 = ni_Ge^2 / N_A     — равновесная конц. неосновных дырок в Ge (см^-3)
        np0 = ni_Si^2 / N_D     — равновесная конц. неосновных электронов в Si
        D = (kT/q) * mu          — соотношение Эйнштейна (Dp, Dn)
        L = sqrt(D * tau)        — диффузионная длина, tau = TAU_MINORITY (константа)

        Диффузионная компонента тока:
          I_диф(V) = A * J0 * (exp(V / Vt) - 1)
    """)),
    ("3. Рекомбинационный ток в ОПЗ (Sah-Noyce-Shockley)", textwrap.dedent("""
        Jrec0 = q * ni_eff * W(0) / (2 * TAU0_SCR)
        I_рек(V) = A * Jrec0 * (exp(V / (n2 * Vt)) - 1)

        n2      — коэффициент неидеальности (вводится пользователем, обычно 1..2)
        ni_eff  = sqrt(ni_Si * ni_Ge)  — эффективная собственная концентрация
                                          (упрощение для гетероперехода)
    """)),
    ("4. Полный ток мезы с учётом Rs и Rsh", textwrap.dedent("""
        I = I_диф(V - I*Rs) + I_рек(V - I*Rs) + (V - I*Rs) / Rsh

        Уравнение неявное относительно I — решается численно методом
        Ньютона (функция solve_iv в simulator/physics.py, 60 итераций
        максимум на точку).
    """)),
    ("5. Встроенный потенциал и ширина ОПЗ", textwrap.dedent("""
        Vbi = Vt * ln( N_D * N_A / ni_eff^2 )

        W(V) = sqrt( 2 * eps * (Vbi - V) / (q * Neff) )
        1 / Neff = 1/N_D + 1/N_A
    """)),
    ("6. Барьерная ёмкость (ВФХ) и резкость перехода", textwrap.dedent("""
        C(V) = eps * A / W(V)

        Общий степенной закон:   C ~ (Vbi - V)^(-1/(m+2))
          m = 0   — резкий (ступенчатый) переход      => C ~ (Vbi-V)^(-1/2)
          m = 1   — линейно-плавный (градиентный)      => C ~ (Vbi-V)^(-1/3)

        Резкость определяется по наклону ln(C) от ln(Vbi - V):
          наклон = -1/(m+2)   =>   m = -1/наклон - 2
        В приложении эта оценка выводится автоматически под графиком ВФХ
        (функция estimate_grading_m), если введённых/загруженных точек
        достаточно и они лежат в области реверсного смещения.
    """)),
    ("7. Подвижность носителей (модель Кофи-Томаса)", textwrap.dedent("""
        mu(N) = mu_min + (mu_max - mu_min) / (1 + (N/Nref)^alpha)

        Константы заданы отдельно для электронов в Si (MU_SI_N) и дырок
        в Ge (MU_GE_P) в simulator/physics.py. Чтобы использовать другой
        набор эмпирических коэффициентов — измените соответствующий
        словарь, формулы (2), (3) автоматически пересчитаются.
    """)),
    ("8. Параметры интерфейса (единицы измерения)", textwrap.dedent("""
        D    — диаметр мезы, мкм
        h    — глубина мезы, мкм (для схемы)
        N_D  — концентрация доноров в Si, см^-3
        N_A  — концентрация акцепторов в Ge, см^-3
        T    — температура, К
        R_s  — последовательное сопротивление, Ом
        R_sh — шунтирующее сопротивление, Ом
        n2   — коэфф. неидеальности рекомбинационного тока (безразмерный)
    """)),
]


def build_formulas_text():
    """Собирает единый текст для окна формул из FORMULA_SECTIONS.
    Ничего внутри этой функции менять не нужно — редактируйте только
    сам список FORMULA_SECTIONS выше."""
    parts = []
    for title, body in FORMULA_SECTIONS:
        parts.append(f"{title}\n{'=' * len(title)}{body}")
    return "\n\n".join(parts)
