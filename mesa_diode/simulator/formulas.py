    def _build_model_part(self, part):
        """Страница части: заголовок с переходом от предыдущей части, оглавление, разделы."""
        page = self.model_pages[part.letter]
        body = page.body
        pad = self.PAD
        self._build_part(body, part)
        toc = _rich_text(body, "", self.bg)
        toc.pack(fill="x", padx=pad, pady=(pad, 4))
        frames = {}
        for section in SECTIONS:
            if section.sid[0] != part.letter:
                continue
            frame = ttk.Frame(body)
            frame.pack(fill="x", padx=pad, pady=(pad, 4))
            frames[section.sid] = frame
            self._build_section(frame, section)
        self._fill_toc(toc, page, frames)
        _rich_text(body, "Номера формул, источники и параметры окна — внутренняя вкладка «Параметры и "
                         "источники». Подробные выкладки — методичка (меню «Справка»).",
                   self.bg, font=SMALL_FONT, foreground="#555555").pack(fill="x", padx=pad, pady=(pad, pad))

    def _fill_toc(self, toc, page, frames):
        """Оглавление части: разделы, по щелчку — переход к разделу."""
        lines = [("В этой части:", None)] + [(f"    {sid}. {SECTION_BY_ID[sid].title}", sid) for sid in frames]
        toc.set([text for text, _key in lines])
        text = toc.text
        text.configure(state="normal")
        text.tag_configure("toc_head", font=BOLD_FONT)
        text.tag_add("toc_head", "1.0", "1.end")
        for index, (_line, key) in enumerate(lines, start=1):
            if key is None:
                continue
            tag = f"toc_{key}"
            text.tag_add(tag, f"{index}.0", f"{index}.end")
            text.tag_configure(tag, foreground=LINK_COLOR)
            text.tag_bind(tag, "<Button-1>", lambda _e, f=frames[key]: page.scroll_to(f))
            text.tag_bind(tag, "<Enter>", lambda _e: text.configure(cursor="hand2"))
            text.tag_bind(tag, "<Leave>", lambda _e: text.configure(cursor="arrow"))
        text.configure(state="disabled")
        toc.fit_height()

