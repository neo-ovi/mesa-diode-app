@dataclass(frozen=True)
class Text:
    text: str
    style: str = "normal"   # normal / small / muted / bold


@dataclass(frozen=True)
class Formula:
    tex: str
    source: str = ""
    badge: str = ""
    fid: str = ""           # ID вида "(2.1)"; у итогов — рамка
    result: bool = False
    note: str = ""          # текст под формулой
    where: tuple = ()       # пояснение символов «где»: (символ mathtext, пояснение)
    ref: str = ""           # пункт методички: «п. 8.1», «гл. 7»
    repeat: bool = False    # формула уже была выше (другая форма той же формулы)


@dataclass(frozen=True)
class Plaque:
    kind: str
    text: str


@dataclass(frozen=True)
class Graph:
    text: str


@dataclass(frozen=True)
class Params:
    rows: tuple             # (символ mathtext, описание, единицы)


@dataclass(frozen=True)
class Current:
    key: str                # ключ функции в CURRENT_VALUES


@dataclass(frozen=True)
class Note:
    key: str                # ключ в preset.notes


@dataclass(frozen=True)
class Section:
    sid: str                # буква части и номер: Б1, Р2, П3
    title: str
    why: str
    blocks: tuple = field(default_factory=tuple)


@dataclass(frozen=True)
class Part:
    letter: str             # Б, Р, П — как буквы режимов у полей во вкладке «Параметры подгонки»
    tab: str                # подпись внутренней вкладки «Модель»
    title: str
    lead: str               # с чего начинается часть: что было раньше и что добавляется


def _t(text, style="normal"):
    return Text(text, style)


