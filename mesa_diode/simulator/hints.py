def section_note(title, mode, model):
    """Короткая строка под заголовком раздела полей (или пустая)."""
    if title == "Ток и эквивалентная схема" and mode != presets.MODE_BASIC and model == "physical":
        return "Ток перехода считается из структуры; здесь — эквивалентная схема и n₂."
    return SECTION_NOTES.get((title, mode), "")


COMPONENT_NAMES = {"emp": "I_{диод}", "d1": "I_{01}", "d2": "I_{02}", "diff": "I_{diff}", "gr": "I_{gr}"}


def curves_caption(model, mode, absent):
    """Строка под графиком: какие компоненты есть у модели, каких нет и где они."""
    from mesa_diode.simulator import models

    current = models.get(model)
    own = ", ".join(COMPONENT_NAMES.get(k, k) for k in current.components)
    others = []
    for other in models.selectable_models():
        missing = [k for k in other.components if k in absent and k not in current.components]
        if missing:
            names = ", ".join(COMPONENT_NAMES.get(k, k) for k in missing)
            others.append(f"{names} — модель «{other.label}»")
    text = f"Компоненты тока этой модели: {own}, шунт I_{{sh}}"
    text += "." if mode == presets.MODE_BASIC else ", утечка I_{L}."
    if others:
        text += " Других компонент здесь нет: " + "; ".join(others) + " (режим «Расширенная», «Модель тока»)."
    if mode == presets.MODE_BASIC:
        text += " Нелинейной утечки I_{L} у простого диода нет."
    return text
