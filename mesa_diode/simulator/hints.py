_MARKUP = re.compile(r"([_^])\{([^{}]*)\}")


def plain(text):
    """Текст без разметки индексов: V_{bi} → Vbi, τ^{bg} → τbg."""
    return _MARKUP.sub(r"\2", text)


def reference(key):
    """«Подробнее: методичка, п. …» для подсказки или пустая строка."""
    ref = METODICHKA_REFS.get(key)
    return f"Подробнее: методичка, {ref}." if ref else ""


