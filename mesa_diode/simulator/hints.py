def field_reason(key, mode, model, scenarios, unused_by_scenario=None):
    """Почему поле key закрыто в режиме mode при модели model; "" — открыто."""
    from mesa_diode.simulator import models

    editable = presets.editable_keys(mode, model)
    if key in editable:
        unused = [sc for sc in scenarios if key in (unused_by_scenario or {}).get(sc, ())]
        if unused and len(unused) == len(scenarios):
            return (f"Не используется при {SCENARIO_NAMES[unused[0]]}: этот слой в сценарии не входит в "
                    "расчёт. Поле откроется при другом типе i-слоя.")
        return ""
    owner = presets.model_for_field(key)
    if owner is not None and owner != model:
        name = models.get(owner).label
        return (f"Нужно только модели тока «{name}». Текущая модель считает ток по-своему (схема справа). "
                f"Выберите «{name}» в режиме «Расширенная», список «Модель тока».")
    target = presets.mode_where_editable(key)
    if key in presets.STORED_KEYS:
        return ("Только хранится в наборе (измерение без формулы в модели). Поле открыто в режиме "
                "«Расширенная».")
    if mode == presets.MODE_BASIC and key in presets.CIRCUIT_KEYS:
        return ("В базовой модели этого нет: простой диод — только диод, R_s и R_sh. Утечка и модуляция R_s "
                "появятся в режиме «Расширенная».")
    if mode == presets.MODE_BASIC:
        return ("Простому диоду этот параметр не нужен: ток задают n и J₀, а не слои. Откроется в режиме "
                f"{MODE_NAMES.get(target, '«Расширенная»')}, где ток можно считать из структуры.")
    if key in presets.FIT_ONLY_KEYS:
        why = "" if model == "physical" else " и только в физической модели"
        return ("Не измеряется: берётся из таблицы (значение в поле используется в расчёте" + why + "). "
                "Менять вручную — в режиме «Подгонка».")
    return f"Не используется в этом режиме. Откроется в режиме {MODE_NAMES.get(target, '')}."


