def error_reference(text):
    """Пункт методички для сообщения text (первое совпадение ERROR_REFS)."""
    for pattern, ref in ERROR_REFS:
        if re.search(pattern, text, flags=re.MULTILINE):
            return ref
    return DEFAULT_ERROR_REF


def with_error_reference(text):
    """Сообщение без разметки индексов и с «Подробнее: методичка, п. …»,
    если ссылки в нём ещё нет."""
    if "методичк" in text:
        return plain(text)
    return plain(f"{text.rstrip()}\nПодробнее: методичка, {error_reference(text)}.")


def with_reference(text, key):
    ref = reference(key)
    return f"{text}\n{ref}" if ref else text


def ideality_failure_text(label, notes, Rs, rs_limit, found):
    """Сообщение блока идеальности: причина, как она связана с R_s, что сделать.

    notes — замечания physics.ideality_from_data; rs_limit —
    physics.series_resistance_limit по той же ВАХ; found — n_эксп определён.
    Возвращает (короткая строка для статуса, полный текст) или ("", "")."""
    rs_too_high = rs_limit == rs_limit and Rs > rs_limit   # rs_limit не nan
    if found and not rs_too_high:
        return "", "; ".join(n.rstrip(".") for n in notes)
    head = (f"n_эксп по ВАХ «{label}» недостоверен." if found
            else f"n_эксп по ВАХ «{label}» не определён.")
    if rs_too_high:
        return ("R_s завышено", (
            f"{head}\nПричина: R_s = {Rs:g} Ом больше, чем допускает эта ВАХ (≈ {rs_limit:.3g} Ом).\n"
            "Связь: n считается по напряжению на самом переходе V_j = V − I·R_s. На верху прямой "
            f"ветви наклон dV/dI ≈ {rs_limit:.3g} Ом; если R_s больше, падение I·R_s растёт быстрее "
            "V, V_j убывает, и точек для подгонки не остаётся.\n"
            f"Что сделать: перепроверьте R_s (контакты и подложка) и задайте R_s < {rs_limit:.3g} Ом.\n"
            f"{reference('ideality')}"))
    reason = "; ".join(n.rstrip(".") for n in notes) or "причина не установлена"
    return ("см. блок идеальности", (
        f"{head}\nПричина: {reason}.\n"
        "Что сделать: снимите «авто» и задайте окно V₁ … V₂ на участке прямой ветви, где "
        "ln I растёт прямолинейно (на Графике 3 локальный n(V) там почти постоянен).\n"
        f"{reference('ideality')}"))


